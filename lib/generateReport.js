/**
 * generateReport.js — the "Doctor Report" PDF.
 *
 * This is the artefact the app tells users to take to a clinician, so the
 * failure modes it had were expensive ones:
 *
 * - **Content fell off the page.** Layout was a single `currentY` counter that
 *   only ever increased and was never checked against the page height. jsPDF
 *   does not paginate for you and does not warn; there was no `addPage()` call
 *   in the file at all. On a report with six cycles and a normal symptom list
 *   the medical disclaimer — the last thing drawn — was simply not in the PDF.
 * - **Blocks overlapped.** The symptom list wrapped over as many lines as it
 *   needed and the cursor then advanced by a hard-coded `currentY += 15`.
 * - **The header overlapped itself.** Name and email sat at fixed offsets
 *   (`marginLeft + 14`, `marginLeft + 45`), about twenty characters of room
 *   for a name at 10 pt.
 * - **The Hindi report was silently unreadable.** The font fetch and the label
 *   set were chosen independently, so a failed fetch produced Devanagari
 *   labels rendered in WinAnsi Helvetica — blank boxes, with nothing but a
 *   `console.warn` to say so.
 *
 * The geometry now lives in `lib/pdf-layout.js`, which is pure and tested. This
 * file is the drawing: it asks the cursor for a y before every block, and
 * cannot place anything below the bottom margin because that is the only way
 * to obtain one.
 */

