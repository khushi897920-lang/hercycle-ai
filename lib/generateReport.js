  en: {
    title: 'HerCycle AI — Doctor Report',
    patient: 'Patient: ',
    email: 'Email: ',
    generated: (d) => `Generated: ${d}`,
    cycleSummary: 'Cycle Summary',
    avgCycleLength: 'Avg cycle length',
    lastPeriodStart: 'Last period start',
    nextPredictedPeriod: 'Next predicted period',
    ovulationEst: 'Ovulation (est.)',
    currentPhase: 'Current phase',
    irregularCycles: 'Irregular cycles',
    cyclesTracked: 'Cycles tracked',
    yes: 'Yes',
    no: 'No',
    recentCycleHistory: 'Recent Cycle History',
    noCyclesLogged: 'No cycles logged yet.',
    startDate: 'Start Date',
    endDate: 'End Date',
    cycleLength: 'Cycle Length',
    days: (n) => `${n} days`,
    recentSymptoms: 'Recent Symptoms (last 15 entries)',
    noSymptomLogs: 'No symptom logs yet.',
    disclaimer: 'This report is generated by HerCycle AI for informational purposes only and is not a medical diagnosis.',
  },
  hi: {
    title: 'हरसायकल एआई — डॉक्टर रिपोर्ट',
    patient: 'रोगी: ',
    email: 'ईमेल: ',
    generated: (d) => `जनरेट किया गया: ${d}`,
    cycleSummary: 'चक्र सारांश',
    avgCycleLength: 'औसत चक्र अवधि',
    lastPeriodStart: 'पिछली माहवारी की शुरुआत',
    nextPredictedPeriod: 'अगली अनुमानित माहवारी',
    ovulationEst: 'ओव्यूलेशन (अनुमानित)',
    currentPhase: 'वर्तमान चरण',
    irregularCycles: 'अनियमित चक्र',
    cyclesTracked: 'दर्ज किए गए चक्र',
    yes: 'हाँ',
    no: 'नहीं',
    recentCycleHistory: 'हाल का चक्र इतिहास',
    noCyclesLogged: 'अभी तक कोई चक्र दर्ज नहीं किया गया।',
    startDate: 'प्रारंभ तिथि',
    endDate: 'समाप्ति तिथि',
    cycleLength: 'चक्र अवधि',
    days: (n) => `${n} दिन`,
    recentSymptoms: 'हाल के लक्षण (पिछले 15 प्रविष्टियाँ)',
    noSymptomLogs: 'अभी तक कोई लक्षण दर्ज नहीं किया गया।',
    disclaimer: 'यह रिपोर्ट हरसायकल एआई द्वारा केवल जानकारी के उद्देश्य से तैयार की गई है और यह कोई चिकित्सा निदान नहीं है।',
  },
