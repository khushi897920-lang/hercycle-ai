/**
 * Builds the download filename.
 *
 * Every export was called `hercycle-report.pdf`, so a second download became
 * `hercycle-report (1).pdf` and a user with three of them in her Downloads
 * folder had no way to tell which was current — in a document whose whole
 * purpose is to be dated.
 *
 * @param {Date|string} generatedAt
 * @returns {string}
 */
export function reportFileName(generatedAt) {
  const date = generatedAt instanceof Date ? generatedAt : new Date(generatedAt)
  const iso = Number.isNaN(date.getTime()) ? null : date.toISOString().slice(0, 10)
  return iso ? `hercycle-report-${iso}.pdf` : 'hercycle-report.pdf'
}

/**
 * Which locale the report can honestly be rendered in.
 *
 * The old code chose labels and font independently:
 *
 *     if (locale === 'hi') { …try to embed the font… }   // may silently fail
 *     const L = LABELS[locale] || LABELS.en              // Hindi labels regardless
 *
 * jsPDF's built-in Helvetica is WinAnsi-encoded and has no Devanagari
 * coverage, so when the font fetch failed — offline, a cache miss, a 404 after
 * an asset path change — every label rendered as blank space or garbage
 * glyphs. The user got a PDF that looked like a real report and handed a page
 * of empty boxes to a doctor. The only signal was a `console.warn`, and
 * `response.ok === false` did not even reach that.
 *
 * A report the reader cannot read is worse than a report in the wrong
 * language, so the fallback is English plus a visible on-page notice
 * explaining what happened.
 *
 * @param {string} requestedLocale
 * @param {boolean} fontEmbedded whether the script for that locale is available
 * @returns {{ locale: string, fellBack: boolean, needsNotice: boolean }}
 */
export function resolveReportLocale(requestedLocale, fontEmbedded) {
  const requested = typeof requestedLocale === 'string' ? requestedLocale : 'en'

  // Locales whose script the built-in PDF fonts cannot render at all.
  const needsEmbeddedFont = requested === 'hi'

  if (!needsEmbeddedFont) return { locale: requested, fellBack: false, needsNotice: false }
  if (fontEmbedded) return { locale: requested, fellBack: false, needsNotice: false }

  return { locale: 'en', fellBack: true, needsNotice: true }
}

/**
 * Renders a measured value, or an explicit "not known" when there is nothing
 * to measure.
 *
 * The summary table read:
 *
 *     const avgLength = pcod?.averageCycleLength || (cycles.length > 0 ? cycles[0].cycle_length : 28)
 *
 * so a user with no cycles logged got "28 days" printed as her average cycle
 * length, in a document a clinician is expected to read as data. A blank is
 * honest; a plausible default is not.
 *
 * @param {unknown} value
 * @param {string} unknownLabel
 * @param {(v: number) => string} [format]
 * @returns {string}
 */
export function renderMeasuredValue(value, unknownLabel, format) {
  if (value === null || value === undefined || value === '') return unknownLabel
  if (typeof value === 'number' && !Number.isFinite(value)) return unknownLabel
  if (typeof format === 'function' && typeof value === 'number') return format(value)
  return String(value)
}

/**
 * Splits a byte array into base64 in chunks.
 *
 * The font was encoded with:
 *
 *     btoa(new Uint8Array(buffer).reduce((data, byte) => data + String.fromCharCode(byte), ''))
 *
 * — a byte-at-a-time string concatenation over ~250 KB, run on the main thread
 * on every single download. Chunking through `String.fromCharCode(...slice)`
 * does the same work in blocks; the chunk size stays well under the argument
 * limit that makes `apply`-style spreading throw on large inputs.
 *
 * @param {ArrayBuffer|Uint8Array} buffer
 * @param {(binary: string) => string} toBase64 the platform's base64 encoder (`btoa`)
 * @param {number} [chunkSize=8192]
 * @returns {string}
 */
export function encodeBase64Chunked(buffer, toBase64, chunkSize = 8192) {
  const bytes = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer)

  let binary = ''
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize))
  }

  return toBase64(binary)
}
