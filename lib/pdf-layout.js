/**
 * Greedy word wrap.
 *
 * jsPDF's own `splitTextToSize` does this, but it is only reachable with a
 * live document — and the bug was never in the wrapping, it was in not
 * knowing *how many lines* the wrap produced. Doing it here means the line
 * count is available before anything is drawn.
 *
 * A single word longer than the width is placed on its own line rather than
 * being broken: hyphenating a symptom name or a URL mid-word in a clinical
 * document is worse than one over-wide line.
 *
 * @param {string} text
 * @param {number} maxWidth
 * @param {(s: string) => number} measureText returns the width of a string
 * @returns {string[]}
 */
export function wrapText(text, maxWidth, measureText) {
  if (typeof text !== 'string' || text.length === 0) return []
  if (typeof measureText !== 'function') return [text]
  if (!Number.isFinite(maxWidth) || maxWidth <= 0) return [text]

  const lines = []

  // Explicit newlines are honoured first, so a caller can force a break.
  for (const paragraph of text.split('\n')) {
    const words = paragraph.split(/\s+/).filter((word) => word.length > 0)

    if (words.length === 0) {
      lines.push('')
      continue
    }

    let current = ''
    for (const word of words) {
      const candidate = current.length === 0 ? word : `${current} ${word}`
      if (measureText(candidate) <= maxWidth || current.length === 0) {
        current = candidate
      } else {
        lines.push(current)
        current = word
      }
    }
    if (current.length > 0) lines.push(current)
  }

  return lines
}

/**
 * How tall a wrapped block will be.
 *
 * This is the function whose absence produced `currentY += 15` after a block
 * that had just wrapped to five lines.
 *
 * @param {string} text
 * @param {{ maxWidth: number, fontSize: number, lineSpacing?: number, measureText: (s: string) => number }} options
 * @returns {{ lines: string[], height: number, lineHeight: number }}
 */
export function measureBlock(text, options) {
  const { maxWidth, fontSize, lineSpacing, measureText } = options || {}
  const lines = wrapText(text, maxWidth, measureText)
  const lineHeight = lineHeightMm(fontSize, lineSpacing)

  return { lines, height: lines.length * lineHeight, lineHeight }
}

