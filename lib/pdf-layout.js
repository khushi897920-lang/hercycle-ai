/**
 * pdf-layout.js — page geometry for the doctor report.
 *
 * ## Why this module exists
 *
 * `lib/generateReport.js` laid out an A4 page with a single `currentY` counter
 * that only ever increased, and never asked whether there was still room:
 *
 *     let currentY = 30
 *     …
 *     currentY += 12
 *     …
 *     currentY = doc.lastAutoTable.finalY + 15
 *     …
 *     doc.text(disclaimer, marginLeft, currentY)
 *
 * jsPDF does not paginate on your behalf and does not warn. Text placed past
 * 297 mm is drawn outside the media box and is simply not in the file. There
 * was no `addPage()` call anywhere in the module, so on a report with six
 * cycles and a normal symptom list the last thing written — *"This report is
 * generated by HerCycle AI for informational purposes only and is not a
 * medical diagnosis"* — fell off the bottom. That is the one line that must
 * never be missing from a document handed to a clinician.
 *
 * Two related failures had the same root:
 *
 * - The symptom block used `maxWidth`, so jsPDF wrapped it over as many lines
 *   as it needed, and then the cursor advanced by a hard-coded `currentY += 15`
 *   regardless. Long lists overlapped whatever came next.
 * - The patient header placed the name and email at fixed offsets
 *   (`marginLeft + 14`, `marginLeft + 45`), giving 31 mm for a name — about
 *   twenty characters at 10 pt. Longer names ran through the "Email:" label,
 *   and in Hindi the label `रोगी: ` is itself wider than its 14 mm allowance.
 *
 * ## The contract
 *
 * Everything here is pure and knows nothing about jsPDF. Text measurement
 * arrives as a callback, because measuring is the one thing that genuinely
 * needs the font metrics the PDF library holds. That keeps the arithmetic —
 * which is where the bugs were — testable in plain Node with a stub measurer.
 */

// ---------------------------------------------------------------------------
// Page geometry
// ---------------------------------------------------------------------------

/** A4 in millimetres, which is jsPDF's default unit for this document. */
export const A4 = Object.freeze({ width: 210, height: 297 })

/**
 * Page margins.
 *
 * `bottom` is 20 rather than the 15 used elsewhere because the footer
 * disclaimer has to fit inside it on the final page without being the thing
 * that decides whether a page break happens.
 */
export const MARGINS = Object.freeze({ top: 20, right: 20, bottom: 20, left: 20 })

/** Where content starts on a fresh page. */
export const CONTENT_TOP = MARGINS.top + 10

/** The widest a full-width block may be. */
export const CONTENT_WIDTH = A4.width - MARGINS.left - MARGINS.right

/**
 * Converts a font size in points to a line height in millimetres.
 *
 * jsPDF measures font size in points and positions in millimetres for this
 * document, and mixing the two silently is how a "15 mm" gap ends up being
 * four lines of 10 pt text. 1 pt = 0.352778 mm; 1.15 is a conventional single
 * line spacing.
 *
 * @param {number} fontSizePt
 * @param {number} [lineSpacing=1.15]
 * @returns {number} millimetres
 */
export function lineHeightMm(fontSizePt, lineSpacing = 1.15) {
  if (!Number.isFinite(fontSizePt) || fontSizePt <= 0) return 0
  return fontSizePt * 0.352778 * lineSpacing
}

// ---------------------------------------------------------------------------
// The cursor
// ---------------------------------------------------------------------------

/**
 * A vertical cursor that knows where the page ends.
 *
 * The whole point is `reserve()`: a caller states how much vertical space the
 * next block needs *before* drawing it, and is told which y to draw at. If the
 * block does not fit, the cursor starts a new page and returns the y at the
 * top of it. Nothing can be drawn past the bottom margin, because the only way
 * to get a y is to ask for one.
 *
 * @param {{ pageHeight?: number, top?: number, bottom?: number, onPageBreak?: () => void }} [options]
 */
export function createCursor(options = {}) {
  const pageHeight = options.pageHeight ?? A4.height
  const top = options.top ?? CONTENT_TOP
  const bottomMargin = options.bottom ?? MARGINS.bottom
  const onPageBreak = typeof options.onPageBreak === 'function' ? options.onPageBreak : null

  const limit = pageHeight - bottomMargin

  let y = top
  let pages = 1
  let breaks = 0

  return {
    /** Current y, in millimetres from the top of the page. */
    get y() {
      return y
    },

    /** How many pages the document has so far. */
    get pageCount() {
      return pages
    },

    /** How many page breaks the cursor has forced. */
    get pageBreaks() {
      return breaks
    },

    /** Vertical space left before the bottom margin. */
    get remaining() {
      return limit - y
    },

    /**
     * Whether a block of `height` fits on the current page.
     *
     * @param {number} height
     * @returns {boolean}
     */
    fits(height) {
      const needed = Number.isFinite(height) && height > 0 ? height : 0
      return y + needed <= limit
    },

    /**
     * Reserves vertical space and returns the y to draw at, starting a new
     * page first if the block will not fit.
     *
     * A block taller than a whole page cannot be made to fit, so it is placed
     * at the top of a fresh page and allowed to overflow — the alternative is
     * an infinite loop of empty pages. Callers that can split their content
     * (wrapped text, table rows) should reserve line by line instead.
     *
     * @param {number} height
     * @returns {number} the y coordinate to draw at
     */
    reserve(height) {
      const needed = Number.isFinite(height) && height > 0 ? height : 0

      if (y + needed > limit && y > top) {
        pages += 1
        breaks += 1
        y = top
        if (onPageBreak) onPageBreak()
      }

      const drawAt = y
      y += needed
      return drawAt
    },

    /**
     * Adds vertical space without drawing anything — the gap between
     * sections.
     *
     * Trailing space at the bottom of a page is dropped rather than pushing a
     * break, so a section that happens to end near the margin does not leave
     * an otherwise blank page behind it.
     *
     * @param {number} height
     */
    gap(height) {
      const needed = Number.isFinite(height) && height > 0 ? height : 0
      y = Math.min(y + needed, limit)
    },

    /**
     * Moves the cursor to an absolute y — used after `autoTable`, which does
     * its own pagination and reports where it finished.
     *
     * @param {number} absoluteY
     */
    moveTo(absoluteY) {
      if (!Number.isFinite(absoluteY)) return
      y = Math.max(top, Math.min(absoluteY, limit))
    },

    /**
     * Records that something else (autoTable) added pages, so `pageCount`
     * stays truthful.
     *
     * @param {number} count
     */
    notePagesAdded(count) {
      if (Number.isFinite(count) && count > 0) pages += count
    },
  }
}

