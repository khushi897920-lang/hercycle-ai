/**
 * Lays out `Label: value` pairs on one line, falling back to one pair per line
 * when they do not fit.
 *
 * Replaces:
 *
 *     doc.text(L.patient, marginLeft, currentY)
 *     doc.text(userName, marginLeft + 14, currentY)
 *     doc.text(L.email, marginLeft + 45, currentY)
 *     doc.text(email, marginLeft + 56, currentY)
 *
 * — 31 mm allotted to a name that is measured at neither 14 nor 45. The
 * offsets also assumed an English label: `रोगी: ` is wider than 14 mm, so the
 * Hindi report overlapped on its very first line.
 *
 * Returns absolute x positions computed from measured widths, and a `stacked`
 * flag telling the caller whether each pair got its own line.
 *
 * @param {Array<{ label: string, value: string }>} pairs
 * @param {{ startX: number, maxWidth: number, gap?: number, measureText: (s: string) => number }} options
 * @returns {{ stacked: boolean, rows: Array<Array<{ label: string, value: string, labelX: number, valueX: number }>> }}
 */
export function layoutLabelledFields(pairs, options) {
  const { startX, maxWidth, measureText } = options || {}
  const gap = options?.gap ?? 6

  const usable = Array.isArray(pairs)
    ? pairs.filter((pair) => pair && typeof pair.label === 'string')
    : []

  if (usable.length === 0) return { stacked: false, rows: [] }
  if (typeof measureText !== 'function') {
    return { stacked: true, rows: usable.map((pair) => [{ ...pair, labelX: startX, valueX: startX }]) }
  }

  // Try one line. Each label is measured, not assumed.
  const singleRow = []
  let x = startX

  for (const pair of usable) {
    const value = typeof pair.value === 'string' ? pair.value : ''
    const labelWidth = measureText(pair.label)
    const valueWidth = measureText(value)

    singleRow.push({ ...pair, value, labelX: x, valueX: x + labelWidth })
    x += labelWidth + valueWidth + gap
  }

  // `- gap` because the last pair does not need trailing separation.
  const totalWidth = x - startX - gap
  if (totalWidth <= maxWidth) return { stacked: false, rows: [singleRow] }

  // Does not fit: one pair per line, which always fits because a line holds
  // one label and one value.
  return {
    stacked: true,
    rows: usable.map((pair) => {
      const value = typeof pair.value === 'string' ? pair.value : ''
      return [{ ...pair, value, labelX: startX, valueX: startX + measureText(pair.label) }]
    }),
  }
}

/**
 * Shortens a value to fit a width, with an ellipsis.
 *
 * The last resort, for a single field with no whitespace to wrap on — an email
 * address, mostly. Truncating is not ideal in a clinical document, so it is
 * only reached when the alternative is drawing over something else.
 *
 * @param {string} text
 * @param {number} maxWidth
 * @param {(s: string) => number} measureText
 * @returns {string}
 */
export function truncateToWidth(text, maxWidth, measureText) {
  if (typeof text !== 'string' || text.length === 0) return ''
  if (typeof measureText !== 'function' || !Number.isFinite(maxWidth) || maxWidth <= 0) return text
  if (measureText(text) <= maxWidth) return text

  const ellipsis = '…'
  let low = 0
  let high = text.length

  // Binary search for the longest prefix that fits with the ellipsis.
  while (low < high) {
    const mid = Math.ceil((low + high) / 2)
    if (measureText(text.slice(0, mid) + ellipsis) <= maxWidth) low = mid
    else high = mid - 1
  }

  return low === 0 ? ellipsis : text.slice(0, low) + ellipsis
}

